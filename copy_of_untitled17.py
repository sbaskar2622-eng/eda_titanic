"""### 📊 Visual Representation of Matrix Sparsity Calculation

Given our Document-Term Matrix `x` representing 6 sentences and 26 unique words:

```text
                  Vocabulary (26 unique words / columns)
               w1   w2   w3   w4   w5  ...  w26
            ┌───────────────────────────────────┐
Sentence 1  │  1    0    1    0    0   ...   0  │ ──┐
Sentence 2  │  0    1    0    1    0   ...   0  │   │
Sentence 3  │  0    0    0    0    1   ...   0  │   │─ Rows (6 sentences)
Sentence 4  │  1    0    0    0    0   ...   1  │   │
Sentence 5  │  0    0    1    0    0   ...   0  │   │
Sentence 6  │  0    1    0    0    0   ...   0  │ ──┘
            └───────────────────────────────────┘
```

---

### 🧮 Step-by-Step Formula Breakdown

| Step | Description | Variable & Formula | Calculation & Value |
| :--- | :--- | :--- | :--- |
| **1** | **Total Cells ($t$)** <br> Total slots available in the grid. | $t = \text{Rows} \times \text{Columns}$ | $6 \times 26 = \mathbf{156}$ |
| **2** | **Non-Zero Cells ($x.nnz$)** <br> Count of slots containing a $1$ (actual word occurrences). | Count of filled cells ($1$s) | Observed count = $\mathbf{32}$ |
| **3** | **Zero Cells ($z$)** <br> Count of empty slots containing $0$. | $z = t - x.nnz$ | $156 - 32 = \mathbf{124}$ |
| **4** | **Sparsity %** <br> The percentage of empty space in the matrix. | $\text{Sparsity} = \frac{z}{t} \times 100$ | $\frac{124}{156} \times 100 = \mathbf{79.5\%}$ |
"""



spam = {"win", "lucky", "credit"}
notspam = {"application"}

def rule(text):
    w = re.findall(r"[a-z]+", text.lower())
    s = sum(word in spam for word in w) - sum(word in notspam for word in w)
    return "spam" if s > 0 else "notspam" if s < 0 else "neutral"
