"""### Machine Learning with a Larger Text Corpus
We will use the **20 Newsgroups dataset** from `sklearn` which contains around 18,000 newsgroup posts on 20 topics. We will build a complete text classification pipeline:
1. Load a subset of categories for demonstration.
2. Convert text to numerical features using `TfidfVectorizer`.
3. Train a `MultinomialNB` classifier.
4. Evaluate the performance using a classification report.
"""

from sklearn.datasets import fetch_20newsgroups
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.metrics import classification_report, accuracy_score

# 1. Select a few categories to keep it clean and fast
categories = ['alt.atheism', 'soc.religion.christian', 'comp.graphics', 'sci.med']

# Load train and test splits
train_data = fetch_20newsgroups(subset='train', categories=categories, shuffle=True, random_state=42)
test_data = fetch_20newsgroups(subset='test', categories=categories, shuffle=True, random_state=42)

print(f"Number of training documents: {len(train_data.data)}")
print(f"Number of testing documents: {len(test_data.data)}")

# 2. Vectorize text content using TF-IDF
vectorizer = TfidfVectorizer(stop_words='english')
X_train = vectorizer.fit_transform(train_data.data)
X_test = vectorizer.transform(test_data.data)

y_train = train_data.target
y_test = test_data.target

# 3. Initialize and train the Naive Bayes model
clf = MultinomialNB(alpha=0.1)
clf.fit(X_train, y_train)

# 4. Predict and evaluate
y_pred = clf.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
print(f"Accuracy: {accuracy * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred, target_names=train_data.target_names))

